<?php

namespace App\Support;

/**
 * A28 · Страны для профиля пользователя (ISO 3166-1 alpha-2).
 * Справочник стран портала (банки, валюты, регуляторы) — отдельный модуль; здесь только подписи для анкеты.
 */
final class Countries
{
    public const LIST = [
        'KZ' => 'Казахстан', 'UZ' => 'Узбекистан', 'KG' => 'Кыргызстан', 'TJ' => 'Таджикистан', 'TM' => 'Туркменистан',
        'RU' => 'Россия', 'BY' => 'Беларусь', 'AM' => 'Армения', 'AZ' => 'Азербайджан', 'GE' => 'Грузия',
        'UA' => 'Украина', 'MD' => 'Молдова', 'MN' => 'Монголия', 'TR' => 'Турция', 'AE' => 'ОАЭ',
        'CN' => 'Китай', 'KR' => 'Корея', 'DE' => 'Германия', 'GB' => 'Великобритания', 'US' => 'США',
    ];

    public static function name(?string $code): ?string
    {
        return $code ? (self::LIST[strtoupper($code)] ?? strtoupper($code)) : null;
    }
}
